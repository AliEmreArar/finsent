"""KAP (Kamuyu Aydınlatma Platformu) disclosure extraction.

Modes (``FINSENT_KAP_MODE``):

* ``sample`` (default) - reads ``data/samples/kap_disclosures_sample.jsonl``,
  a synthetic, clearly-labelled dataset generated by
  ``scripts/generate_kap_sample.py``. Every record has ``source="sample"``.
* ``live`` - real disclosures from KAP's public disclosure API (see
  ``kap_live.py``): one list request per weekday, mechanical notices dropped,
  full text downloaded for price-relevant notices.
"""
from __future__ import annotations

import hashlib
import logging
import re
import unicodedata
from datetime import date, datetime
from pathlib import Path

import pandas as pd

from .config import Settings

log = logging.getLogger(__name__)

DISCLOSURE_COLUMNS = [
    "disclosure_id", "disclosure_index", "symbol", "company_title", "published_at",
    "disclosure_class", "subject", "summary", "body", "url", "source", "content_hash",
]


def normalize_text(text: str | None) -> str:
    text = unicodedata.normalize("NFKC", text or "")
    text = text.replace(" ", " ")
    return re.sub(r"\s+", " ", text).strip()


def content_hash(symbol: str, subject: str, summary: str, body: str, day: str = "") -> str:
    """Hash of the disclosure *content* on its publication day - catches same-day re-sends that
    get a new index, while routine notices that repeat the same wording on other days (daily
    buy-back reports, liquidity-provider reports...) stay distinct."""
    payload = "\x1f".join(normalize_text(x).casefold() for x in (symbol, subject, summary, body, day))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _finalize(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return pd.DataFrame(columns=DISCLOSURE_COLUMNS)
    for col in ("subject", "summary", "body", "company_title"):
        df[col] = df[col].map(normalize_text)
    df["symbol"] = df["symbol"].str.upper().str.strip()
    df["published_at"] = pd.to_datetime(df["published_at"])
    df["disclosure_id"] = df["source"] + ":" + df["disclosure_index"].astype(str)
    df["content_hash"] = [
        content_hash(r.symbol, r.subject, r.summary, r.body, str(r.published_at.date())) for r in df.itertuples()
    ]
    return df[DISCLOSURE_COLUMNS].reset_index(drop=True)


def load_sample(settings: Settings, start: date, end: date) -> pd.DataFrame:
    path = Path(settings.kap_sample_path)
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found - run `python scripts/generate_kap_sample.py` first"
        )
    df = pd.read_json(path, lines=True, dtype={"disclosure_index": "int64"})
    published = pd.to_datetime(df["published_at"]).dt.date
    df = df[(published >= start) & (published <= end)].copy()
    log.info("sample KAP disclosures %s..%s: %d", start, end, len(df))
    return _finalize(df)


def load_live(settings: Settings, start: date, end: date) -> pd.DataFrame:
    """Real KAP disclosures (bodies are filled later, only for new rows - see jobs)."""
    from .kap_live import KapLiveClient

    raw = KapLiveClient(settings).fetch_raw(start, end)
    if raw.empty:
        return pd.DataFrame(columns=DISCLOSURE_COLUMNS)
    df = _finalize(raw)
    # a notice naming several stocks yields one row per stock: suffix all but the first id
    dup = df.duplicated("disclosure_id", keep="first")
    df.loc[dup, "disclosure_id"] = df.loc[dup, "disclosure_id"] + ":" + df.loc[dup, "symbol"]
    return df


def extract_disclosures(settings: Settings, start: date, end: date) -> pd.DataFrame:
    from .kap_live import NOISE_SUBJECTS

    if settings.kap_mode == "sample":
        df = load_sample(settings, start, end)
    elif settings.kap_mode == "live":
        df = load_live(settings, start, end)
    else:
        raise ValueError(f"unknown KAP mode: {settings.kap_mode}")
    # same noise filter for every source, so ingested == scored == served
    return df[~df["subject"].isin(NOISE_SUBJECTS)].reset_index(drop=True)


def to_records(df: pd.DataFrame) -> list[dict]:
    out = df.copy()
    out["published_at"] = out["published_at"].map(
        lambda t: t.isoformat() if isinstance(t, (datetime, pd.Timestamp)) else t
    )
    return out.to_dict(orient="records")
